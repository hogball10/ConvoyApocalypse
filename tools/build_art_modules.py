"""Convert the ConvoyKit Blender exports into Luau data modules.

Reads:
  <kit>/meshes/*.json   one mesh per file  -> ConvoyArt       (folder "world")
  <kit>/custom.json     {"items":[...]}    -> ConvoyArt / ConvoyArtSkins
  <kit>/items/*.json    one item per file  -> ConvoyArt / ConvoyArtSkins
                        (overrides a same-named mesh, e.g. build_zombie.py)

Writes:
  src/shared/ReplicatedStorage/ConvoyShared/ArtData/<Name>.luau

Geometry is emitted as whitespace-separated strings rather than Luau table
literals: a few of these meshes have >1000 triangles and a literal table that
size is slow to parse and awkward to diff. Vertices are rebased so the part's
own bounding-box centre sits at the origin, and that centre is kept as
CenterX/Y/Z so ArtKit.Place can put the piece back where it was modelled.

Each part also gets a content hash, and a meshId when tools/art_mesh_ids.json
maps that hash to an uploaded Roblox mesh asset. Meshes built at runtime from
an EditableMesh never reach clients, so players only see parts with a meshId.
Upload the missing ones from Studio, add them to the JSON, and run this again.

Run from the project root:  python tools/build_art_modules.py
"""

import hashlib
import json
import os
import sys

KIT = r"C:\Users\TJ\Documents\ConvoyKit"
TOOLS = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(TOOLS, "..", "src", "shared", "ReplicatedStorage", "ConvoyShared", "ArtData")
MESH_IDS = os.path.join(TOOLS, "art_mesh_ids.json")

# Blender-side material names that do not match a Roblox Enum.Material.
MATERIAL_ALIAS = {
    "Rubber": "SmoothPlastic",
    "Stone": "Slate",
}


def num(value):
    """Trim floats so the generated source stays small and stable."""
    rounded = round(float(value), 4)
    if rounded == int(rounded):
        return str(int(rounded))
    return repr(rounded)


def encode_part(part):
    verts = part["verts"]
    tris = part["tris"]
    center = part.get("center") or [0.0, 0.0, 0.0]
    cx, cy, cz = (float(c) for c in center)

    # Rebase onto the bounding-box centre.
    flat_verts = []
    for vx, vy, vz in verts:
        flat_verts.append(num(vx - cx))
        flat_verts.append(num(vy - cy))
        flat_verts.append(num(vz - cz))

    flat_tris = []
    for tri in tris:
        if len(tri) != 3:
            raise ValueError(f"{part['name']}: non-triangle face {tri}")
        for idx in tri:
            if not 1 <= idx <= len(verts):
                raise ValueError(f"{part['name']}: vertex index {idx} out of range")
            flat_tris.append(str(int(idx)))

    material = part.get("material") or "SmoothPlastic"
    material = MATERIAL_ALIAS.get(material, material)
    color = part.get("color") or [160, 160, 160]

    verts_text = " ".join(flat_verts)
    tris_text = " ".join(flat_tris)
    digest = hashlib.sha1(f"{verts_text}|{tris_text}".encode("utf-8")).hexdigest()[:16]

    return {
        "hash": digest,
        "name": part["name"],
        "material": material,
        "color": [int(c) for c in color],
        "accent": bool(part.get("accent")),
        "center": (cx, cy, cz),
        "verts": verts_text,
        "tris": tris_text,
        "nv": len(verts),
        "nt": len(tris),
    }


def luau_quote(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def load_mesh_ids():
    if not os.path.exists(MESH_IDS):
        return {}
    with open(MESH_IDS, encoding="utf-8") as handle:
        return json.load(handle)


def write_module(item_name, folder, parts, mesh_ids):
    lines = [
        "--!strict",
        "-- GENERATED by tools/build_art_modules.py -- do not edit by hand.",
        f"-- Source: ConvoyKit Blender export ({item_name}).",
        "",
        "return {",
        f"\tname = {luau_quote(item_name)},",
        f"\tfolder = {luau_quote(folder)},",
        "\tparts = {",
    ]
    for part in parts:
        cx, cy, cz = part["center"]
        r, g, b = part["color"]
        lines += [
            "\t\t{",
            f"\t\t\tname = {luau_quote(part['name'])},",
            f"\t\t\tmaterial = {luau_quote(part['material'])},",
            f"\t\t\tcolor = {{ {r}, {g}, {b} }},",
            f"\t\t\taccent = {'true' if part['accent'] else 'false'},",
            f"\t\t\tcenter = {{ {num(cx)}, {num(cy)}, {num(cz)} }},",
            f"\t\t\thash = {luau_quote(part['hash'])},",
        ]
        if part["hash"] in mesh_ids:
            lines.append(f"\t\t\tmeshId = {luau_quote('rbxassetid://' + str(mesh_ids[part['hash']]))},")
        lines += [
            f"\t\t\tvertexCount = {part['nv']},",
            f"\t\t\ttriangleCount = {part['nt']},",
            f"\t\t\tverts = {luau_quote(part['verts'])},",
            f"\t\t\ttris = {luau_quote(part['tris'])},",
            "\t\t},",
        ]
    lines += ["\t},", "}", ""]

    path = os.path.join(OUT, f"{item_name}.luau")
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    return path


def main():
    os.makedirs(OUT, exist_ok=True)

    # Clear previously generated modules so renamed meshes do not linger.
    for stale in os.listdir(OUT):
        if stale.endswith(".luau"):
            os.remove(os.path.join(OUT, stale))

    # name -> (folder, encoded parts). A later entry replaces an earlier one
    # with the same name, so items/*.json can override a kit mesh.
    modules = {}

    mesh_dir = os.path.join(KIT, "meshes")
    for filename in sorted(os.listdir(mesh_dir)):
        if not filename.endswith(".json"):
            continue
        with open(os.path.join(mesh_dir, filename), encoding="utf-8") as handle:
            raw = json.load(handle)
        modules[raw["name"]] = ("world", [encode_part(raw)])

    custom_path = os.path.join(KIT, "custom.json")
    with open(custom_path, encoding="utf-8") as handle:
        items = json.load(handle)["items"]

    item_dir = os.path.join(KIT, "items")
    if os.path.isdir(item_dir):
        for filename in sorted(os.listdir(item_dir)):
            if filename.endswith(".json"):
                with open(os.path.join(item_dir, filename), encoding="utf-8") as handle:
                    items.append(json.load(handle))

    for item in items:
        folder = "skin" if item.get("folder") == "skin" else "world"
        modules[item["name"]] = (folder, [encode_part(p) for p in item["parts"]])

    mesh_ids = load_mesh_ids()
    materials = set()
    missing = 0
    for name in sorted(modules):
        folder, parts = modules[name]
        write_module(name, folder, parts, mesh_ids)
        materials.update(p["material"] for p in parts)
        missing += sum(1 for p in parts if p["hash"] not in mesh_ids)
        nv = sum(p["nv"] for p in parts)
        nt = sum(p["nt"] for p in parts)
        print(f"  {name:<16} {folder:<6} parts={len(parts):<3} verts={nv:<6} tris={nt}")
    print(f"\n{len(modules)} art modules -> {os.path.normpath(OUT)}")
    print("materials used: " + ", ".join(sorted(materials)))
    if missing:
        print(f"{missing} part(s) have no uploaded mesh yet -- players will not see them")


if __name__ == "__main__":
    sys.exit(main())
